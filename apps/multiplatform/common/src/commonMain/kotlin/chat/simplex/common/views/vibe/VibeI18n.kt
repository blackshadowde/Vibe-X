  private fun lang(): String =
    (runCatching { appPreferences.appLanguage.get() }.getOrNull()?.takeIf { it.isNotBlank() } ?: java.util.Locale.getDefault().language).substringBefore('-').substringBefore('_')

  fun t(en: String): String = when (lang()) {
    "hi" -> hi[en]
    "te" -> te[en]
    else -> null
  } ?: en
}

